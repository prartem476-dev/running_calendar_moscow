/**
 * Определяет макрорегион, страну и визовый статус для событий из РФ и СНГ.
 */
export function classifyEventGeography(locationOrText, title = '', isMoscowOrMoFn = null) {
  const combined = `${locationOrText || ''} ${title || ''}`.toLowerCase();

  if (REGION_KEYWORDS.cis.some((k) => combined.includes(k))) {
    let country = 'СНГ';
    if (combined.includes('минск') || combined.includes('беларус') || combined.includes('брест') || combined.includes('гродно')) country = 'Беларусь';
    else if (combined.includes('алмат') || combined.includes('астан') || combined.includes('казахстан')) country = 'Казахстан';
    else if (combined.includes('самарканд') || combined.includes('ташкент') || combined.includes('бухар') || combined.includes('узбекистан')) country = 'Узбекистан';
    else if (combined.includes('ереван') || combined.includes('армени')) country = 'Армения';
    else if (combined.includes('баку') || combined.includes('азербайджан')) country = 'Азербайджан';
    else if (combined.includes('тбилиси') || combined.includes('грузи') || combined.includes('казбег')) country = 'Грузия';
    else if (combined.includes('бишкек') || combined.includes('иссык-кул')) country = 'Кыргызстан';
    return {
      matched: true,
      region: 'СНГ',
      country,
      scope: 'cis',
      visa_status: 'no_visa',
    };
  }

  if (REGION_KEYWORDS.goldenRing.some((k) => combined.includes(k))) {
    return {
      matched: true,
      region: 'Золотое кольцо',
      country: 'Россия',
      scope: 'russia',
      visa_status: 'domestic',
    };
  }

  if (REGION_KEYWORDS.spb.some((k) => combined.includes(k))) {
    return {
      matched: true,
      region: 'Санкт-Петербург',
      country: 'Россия',
      scope: 'russia',
      visa_status: 'domestic',
    };
  }

  if (REGION_KEYWORDS.sochi.some((k) => combined.includes(k))) {
    return {
      matched: true,
      region: 'Сочи и Кавказ',
      country: 'Россия',
      scope: 'russia',
      visa_status: 'domestic',
    };
  }

  if (REGION_KEYWORDS.kazan.some((k) => combined.includes(k))) {
    return {
      matched: true,
      region: 'Казань и Поволжье',
      country: 'Россия',
      scope: 'russia',
      visa_status: 'domestic',
    };
  }

  if (REGION_KEYWORDS.uralSiberia.some((k) => combined.includes(k))) {
    return {
      matched: true,
      region: 'Урал и Сибирь',
      country: 'Россия',
      scope: 'russia',
      visa_status: 'domestic',
    };
  }

  if (isMoscowOrMoFn) {
    const [isMsk, mskRegion] = isMoscowOrMoFn(combined);
    if (isMsk) {
      return {
        matched: true,
        region: mskRegion,
        country: 'Россия',
        scope: 'russia',
        visa_status: 'domestic',
      };
    }
  }

  return {
    matched: false,
    region: 'Москва',
    country: 'Россия',
    scope: 'russia',
    visa_status: 'domestic',
  };
}

